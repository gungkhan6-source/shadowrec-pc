// RTL (Right-to-Left) diller listesi - şimdilik sadece Arapça
export const RTL_LANGUAGES = ['ar']

export const LANGUAGES = [
  { id:'en', label:'English',  flag:'🇬🇧' },
  { id:'tr', label:'Türkçe',   flag:'🇹🇷' },
  { id:'de', label:'Deutsch',  flag:'🇩🇪' },
  { id:'fr', label:'Français', flag:'🇫🇷' },
  { id:'it', label:'Italiano', flag:'🇮🇹' },
  { id:'es', label:'Español',  flag:'🇪🇸' },
  { id:'ru', label:'Русский',  flag:'🇷🇺' },
  { id:'zh', label:'中文',     flag:'🇨🇳' },
  { id:'ar', label:'العربية',  flag:'🇸🇦' },
]

const LangContext = createContext({ lang:'en', setLang:()=>{}, t:(k)=>k, isRTL:false })

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem('novarec.lang') || 'en' } catch { return 'en' }
  })
  const setLang = (newLang) => {
    setLangState(newLang)
    try { localStorage.setItem('novarec.lang', newLang) } catch {}
    // RTL/LTR otomatik switch (HTML dir attribute)
    try {
      document.documentElement.dir = RTL_LANGUAGES.includes(newLang) ? 'rtl' : 'ltr'
      document.documentElement.lang = newLang
    } catch {}
  }
  
  // İlk yüklemede RTL/LTR ayarla
  React.useEffect(() => {
    try {
      document.documentElement.dir = RTL_LANGUAGES.includes(lang) ? 'rtl' : 'ltr'
      document.documentElement.lang = lang
    } catch {}
  }, [lang])
  
  const isRTL = RTL_LANGUAGES.includes(lang)
  
  const t = (key, vars) => {
    const dict = STRINGS[lang] || STRINGS.en
    let str = dict[key] || STRINGS.en[key] || key
    if (vars) Object.keys(vars).forEach(k => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k])
    })
    return str
  }
  return <LangContext.Provider value={{ lang, setLang, t, isRTL }}>{children}</LangContext.Provider>
}

export function useLang() { return useContext(LangContext) }
